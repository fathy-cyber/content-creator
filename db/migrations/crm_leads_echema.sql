-- CRM Module Database Schema
-- This schema defines tables for contacts, leads, and activities.
-- Compatible with PostgreSQL (Supabase).

-- ==============================
-- CRM Contacts
-- ==============================
CREATE TABLE IF NOT EXISTS crm_contacts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  company VARCHAR(255),
  job_title VARCHAR(255),
  type VARCHAR(32) CHECK (type IN ('individual', 'company')) DEFAULT 'individual',
  category VARCHAR(32) CHECK (category IN ('customer', 'vendor', 'prospect', 'partner', 'other')) DEFAULT 'prospect',
  email VARCHAR(255),
  phone VARCHAR(64),
  mobile VARCHAR(64),
  website VARCHAR(255),
  address TEXT,
  city VARCHAR(128),
  state VARCHAR(128),
  country VARCHAR(128) DEFAULT 'Tunisia',
  notes TEXT,
  assigned_to VARCHAR(255),
  active BOOLEAN DEFAULT TRUE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW()),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW())
);

-- Indexes for faster lookups
CREATE INDEX IF NOT EXISTS idx_crm_contacts_name ON crm_contacts(name);
CREATE INDEX IF NOT EXISTS idx_crm_contacts_email ON crm_contacts(email);
CREATE INDEX IF NOT EXISTS idx_crm_contacts_company ON crm_contacts(company);
CREATE INDEX IF NOT EXISTS idx_crm_contacts_category ON crm_contacts(category);
CREATE INDEX IF NOT EXISTS idx_crm_contacts_active ON crm_contacts(active);

-- Trigger to update updated_at on row changes
CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = TIMEZONE('utc', NOW());
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE TRIGGER update_crm_contacts_updated_at
BEFORE UPDATE ON crm_contacts
FOR EACH ROW
EXECUTE FUNCTION update_updated_at_column();

-- ==============================
-- CRM Leads
-- ==============================
CREATE TABLE IF NOT EXISTS crm_leads (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contact_id BIGINT REFERENCES crm_contacts(id) ON DELETE SET NULL,
  company VARCHAR(255),
  email VARCHAR(255),
  phone VARCHAR(64),
  stage VARCHAR(32) CHECK (stage IN ('new', 'qualified', 'proposition', 'negotiation', 'won', 'lost')) DEFAULT 'new',
  priority VARCHAR(32) CHECK (priority IN ('low', 'medium', 'high', 'urgent')) DEFAULT 'medium',
  expected_revenue NUMERIC(12,2),
  probability INTEGER CHECK (probability >= 0 AND probability <= 100) DEFAULT 10,
  source VARCHAR(64) CHECK (source IN ('website', 'facebook', 'instagram', 'whatsapp', 'referral', 'cold-call', 'event', 'other')),
  expected_close_date DATE,
  description TEXT,
  notes TEXT,
  assigned_to VARCHAR(255),
  lost_reason VARCHAR(255),
  active BOOLEAN DEFAULT TRUE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW()),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW())
);

CREATE INDEX IF NOT EXISTS idx_crm_leads_stage ON crm_leads(stage);
CREATE INDEX IF NOT EXISTS idx_crm_leads_contact ON crm_leads(contact_id);
CREATE INDEX IF NOT EXISTS idx_crm_leads_active ON crm_leads(active);

CREATE OR REPLACE TRIGGER update_crm_leads_updated_at
BEFORE UPDATE ON crm_leads
FOR EACH ROW
EXECUTE FUNCTION update_updated_at_column();

-- ==============================
-- CRM Activities
-- ==============================
CREATE TABLE IF NOT EXISTS crm_activities (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  summary VARCHAR(255) NOT NULL,
  type VARCHAR(32) CHECK (type IN ('call', 'meeting', 'email', 'whatsapp', 'note', 'task')) NOT NULL,
  date TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW()),
  description TEXT,
  contact_id BIGINT REFERENCES crm_contacts(id) ON DELETE CASCADE,
  lead_id BIGINT REFERENCES crm_leads(id) ON DELETE CASCADE,
  assigned_to VARCHAR(255),
  done BOOLEAN DEFAULT FALSE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW())
);

CREATE INDEX IF NOT EXISTS idx_crm_activities_contact ON crm_activities(contact_id);
CREATE INDEX IF NOT EXISTS idx_crm_activities_lead ON crm_activities(lead_id);
CREATE INDEX IF NOT EXISTS idx_crm_activities_date ON crm_activities(date);
CREATE INDEX IF NOT EXISTS idx_crm_activities_done ON crm_activities(done);
